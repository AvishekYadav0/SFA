import { useCallback, useEffect, useState } from 'react';
import { AlertCircle, RefreshCw, ShieldCheck } from 'lucide-react';
import { platformAdminApi } from '../services/platformAdminApi';

function formatValue(value) {
  if (value == null) return '—';
  return typeof value === 'string' ? value : JSON.stringify(value);
}

export default function PlatformAdminAuditLogs() {
  const [logs, setLogs] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');

  const load = useCallback(async () => {
    setLoading(true);
    setError('');
    try {
      const { data } = await platformAdminApi.getAuditLogs();
      setLogs(Array.isArray(data.data) ? data.data : []);
    } catch (requestError) {
      setError(requestError.response?.data?.message || 'Unable to load audit logs.');
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => { load(); }, [load]);

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div><p className="text-xs font-semibold uppercase tracking-[0.2em] text-blue-600">Platform</p><h1 className="mt-1 text-3xl font-bold text-slate-900">Audit Logs</h1><p className="mt-1 text-sm text-slate-500">Read-only activity records generated by the backend.</p></div>
        <div className="flex items-center gap-2"><div className="inline-flex items-center gap-2 rounded-xl bg-white px-3 py-2 text-sm text-slate-700 shadow-sm ring-1 ring-slate-200"><ShieldCheck className="h-4 w-4" />{logs.length} records</div><button type="button" onClick={load} className="inline-flex items-center gap-2 rounded-xl border border-slate-200 bg-white px-3 py-2 text-sm font-medium text-slate-700 hover:bg-slate-50"><RefreshCw className="h-4 w-4" />Refresh</button></div>
      </div>

      {error ? (
        <div role="alert" className="rounded-2xl border border-red-200 bg-white p-6 text-red-700 shadow-sm"><div className="flex items-center gap-2"><AlertCircle className="h-5 w-5" />{error}</div><button type="button" onClick={load} className="mt-4 inline-flex items-center gap-2 rounded-lg bg-red-50 px-3 py-2 text-sm font-medium hover:bg-red-100"><RefreshCw className="h-4 w-4" />Retry</button></div>
      ) : (
        <div className="overflow-hidden rounded-2xl border border-slate-200 bg-white shadow-sm">
          <div className="overflow-x-auto"><table className="min-w-full text-left text-sm">
            <thead className="bg-slate-50 text-slate-600"><tr>{['Action', 'Company', 'Admin', 'Date & Time', 'Description', 'Previous Value', 'New Value'].map((heading) => <th key={heading} className="whitespace-nowrap px-4 py-3 font-medium">{heading}</th>)}</tr></thead>
            <tbody>{loading ? <tr><td className="px-4 py-10 text-center text-slate-500" colSpan="7">Loading audit logs...</td></tr> : logs.length ? logs.map((log) => (
              <tr key={log._id} className="border-t border-slate-100 align-top">
                <td className="whitespace-nowrap px-4 py-3 font-medium text-slate-900">{log.action}</td>
                <td className="whitespace-nowrap px-4 py-3 text-slate-600">{log.company || 'Platform'}</td>
                <td className="whitespace-nowrap px-4 py-3 text-slate-600">{log.admin || 'System'}</td>
                <td className="whitespace-nowrap px-4 py-3 text-slate-600">{log.createdAt ? new Date(log.createdAt).toLocaleString() : '—'}</td>
                <td className="min-w-52 px-4 py-3 text-slate-600">{log.description || '—'}</td>
                <td className="max-w-64 break-words px-4 py-3 text-xs text-slate-500">{formatValue(log.previousValue)}</td>
                <td className="max-w-64 break-words px-4 py-3 text-xs text-slate-500">{formatValue(log.newValue)}</td>
              </tr>
            )) : <tr><td className="px-4 py-12 text-center text-slate-500" colSpan="7">No audit records are stored yet.</td></tr>}</tbody>
          </table></div>
        </div>
      )}
    </div>
  );
}
